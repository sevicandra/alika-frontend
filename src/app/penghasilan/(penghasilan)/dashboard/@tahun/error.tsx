"use client";

import { useEffect } from "react";

export default function Error({
  error,
  reset,
}: {
  error: Error & { digest?: string };
  reset: () => void;
}) {
  useEffect(() => {
    console.error(error);
  }, [error]);

  return (
    <div className="w-full">
      <button className="btn btn-xs btn-outline" onClick={() => reset()}>Try again</button>
    </div>
  );
}
